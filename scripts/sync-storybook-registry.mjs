import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Parse only static published CSS data. Never execute Storybook JavaScript.
export function extractRegistry(css, index, baseUrl, cssUrl) {
  const variables = {};
  for (const match of css.matchAll(/:root\s*\{([^{}]*)\}/g)) {
    for (const declaration of match[1].matchAll(/(--(?:color|spacing|radius|typography|font-family)[\w-]*)\s*:\s*([^;{}]+)/g)) {
      variables[declaration[1]] = declaration[2].trim();
    }
  }
  const utilities = {};
  for (const match of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    // Complex, conditional and pseudo selectors are checked through page CSS,
    // rather than treating their class name as unconditional evidence.
    const selector = match[1].trim();
    if (!/^\.[\w-]+$/.test(selector)) continue;
    const declarations = {};
    for (const declaration of match[2].matchAll(/([\w-]+)\s*:\s*([^;{}]+)/g)) {
      const references = [...declaration[2].matchAll(/var\(\s*(--[\w-]+)/g)].map(item => item[1]);
      if (references.length && references.every(name => Object.hasOwn(variables, name))) {
        declarations[declaration[1]] = declaration[2].trim();
      }
    }
    if (Object.keys(declarations).length) utilities[selector.slice(1)] = declarations;
  }
  const docs = Object.fromEntries(Object.values(index.entries || {})
    .filter(entry => entry.type === 'docs')
    .map(entry => [entry.title, `${baseUrl}/?path=/docs/${entry.id}`]));
  if (Object.keys(variables).length < 10 || !docs['Foundation/Colors/Semantic']) {
    throw new Error('Published FDS variables or Storybook docs missing; existing registry preserved');
  }
  return { source: { baseUrl, cssUrl, capturedAt: new Date().toISOString(),
    sha256: createHash('sha256').update(css).digest('hex') }, variables, utilities, docs };
}

async function read(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(15000) });
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.text();
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const baseUrl = (process.argv[2] || 'http://192.168.100.108:6006').replace(/\/$/, '');
  const [html, indexText] = await Promise.all([read(`${baseUrl}/iframe.html`), read(`${baseUrl}/index.json`)]);
  const cssLinks = [...html.matchAll(/<link\b[^>]*>/g)].map(match => match[0])
    .filter(tag => /rel="stylesheet"/.test(tag))
    .map(tag => tag.match(/href="([^"]+)"/)?.[1]).filter(Boolean);
  if (!cssLinks.length) throw new Error('Storybook CSS not found');
  const cssUrls = cssLinks.map(path => new URL(path, `${baseUrl}/`).href);
  const css = (await Promise.all(cssUrls.map(read))).join('\n');
  const registry = extractRegistry(css, JSON.parse(indexText), baseUrl, cssUrls.join(', '));
  await writeFile(new URL('../storybook-registry.js', import.meta.url),
    `// Generated by scripts/sync-storybook-registry.mjs from published FDS CSS.\n(function(root) {\n  const registry = ${JSON.stringify(registry, null, 2)};\n  root.FDSStorybookRegistry = registry;\n  if (typeof module !== 'undefined') module.exports = registry;\n})(globalThis);\n`);
  console.log(`FDS registry: ${Object.keys(registry.variables).length} variables, ${Object.keys(registry.utilities).length} utilities, ${Object.keys(registry.docs).length} docs`);
}
